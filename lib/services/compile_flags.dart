import 'dart:io';

import 'package:flutter/foundation.dart';

/// What happened when [CompileFlagsEnsurer.ensure] looked at a workspace.
enum CompileFlagsOutcome {
  /// `compile_flags.txt` was missing and is now written.
  created,

  /// A file this class generated in its old (broken) format was rewritten.
  upgraded,

  /// A `compile_flags.txt` was already there; it is never overwritten.
  alreadyPresent,

  /// No directory to write into.
  unavailable,

  /// The file could not be written.
  failed,
}

/// Writes the `compile_flags.txt` clangd needs to find the macOS SDK headers.
///
/// Without it clangd still parses but reports `'stdio.h' file not found` and
/// completion is worthless, so — per the owner's decision — the file is created
/// automatically when a C/C++ file is opened. An existing file is never
/// touched: the user's flags win, with one exception — a file **we** generated
/// in an older, broken format is rewritten (see [buildContents]).
///
/// Two format rules matter, both learned from the real clangd:
/// * `compile_flags.txt` has **no comment syntax**. A `#` line is passed to the
///   compiler as an argument, the command becomes invalid and clangd loses the
///   SDK include paths again (`'iostream' file not found`, then a cascade of
///   "undeclared identifier 'std'" errors for code that compiles fine).
/// * One **argument** per line, so `-isysroot` and its path must be separate
///   lines; `-isysroot /path` as a single line is one bogus argument.
class CompileFlagsEnsurer {
  CompileFlagsEnsurer({
    Future<String?> Function()? sdkPathResolver,
    bool Function(String path)? fileExists,
  }) : _sdkPathResolver = sdkPathResolver ?? _xcrunSdkPath,
       _fileExists = fileExists ?? ((path) => File(path).existsSync());

  /// Name of the file clangd reads from the directory of the source file (or a
  /// parent directory).
  static const String fileName = 'compile_flags.txt';

  /// First line of the broken format this class used to write (comment header +
  /// one-line `-isysroot`). Detecting it lets an upgrade repair the file without
  /// touching a file a user wrote themselves.
  static const String legacyHeader =
      '# Generated by Classic Code Editor for clangd.';

  final Future<String?> Function() _sdkPathResolver;
  final bool Function(String path) _fileExists;

  /// Creates [fileName] in [directory] when it is missing.
  Future<CompileFlagsOutcome> ensure(String? directory) async {
    if (directory == null || directory.trim().isEmpty) {
      return CompileFlagsOutcome.unavailable;
    }

    final path = '$directory${Platform.pathSeparator}$fileName';
    final file = File(path);
    final existed = _fileExists(path);
    if (existed && !_isLegacyGenerated(file)) {
      return CompileFlagsOutcome.alreadyPresent;
    }

    final sdkPath = await _sdkPathResolver();
    final contents = buildContents(sdkPath);
    if (contents.isEmpty) {
      // No SDK path means no usable flag: writing an empty file would give
      // clangd an empty command, which is no better than no file at all.
      return existed
          ? CompileFlagsOutcome.alreadyPresent
          : CompileFlagsOutcome.unavailable;
    }

    try {
      await file.writeAsString(contents, flush: true);
      return existed
          ? CompileFlagsOutcome.upgraded
          : CompileFlagsOutcome.created;
    } on FileSystemException catch (e) {
      debugPrint('Could not write $path: $e');
      return CompileFlagsOutcome.failed;
    }
  }

  /// Contents of a generated `compile_flags.txt`, or an empty string when the
  /// SDK path is unknown (the file is then not written at all).
  ///
  /// Deliberately no comments — clangd has no comment syntax here and a `#` line
  /// silently breaks the whole command — and `-isysroot` and its value on two
  /// lines, because every line is one argument.
  @visibleForTesting
  static String buildContents(String? sdkPath) {
    if (sdkPath == null || sdkPath.trim().isEmpty) return '';
    return '-isysroot\n${sdkPath.trim()}\n';
  }

  /// Whether [file] is one this class wrote in its old, broken format.
  static bool _isLegacyGenerated(File file) {
    try {
      return file.readAsLinesSync().first.trim() == legacyHeader;
    } catch (e) {
      debugPrint('Could not read ${file.path}: $e');
      return false;
    }
  }

  static Future<String?> _xcrunSdkPath() async {
    try {
      final result = await Process.run('xcrun', <String>['--show-sdk-path']);
      if (result.exitCode != 0) return null;
      final path = (result.stdout as String).trim();
      return path.isEmpty ? null : path;
    } on ProcessException catch (e) {
      debugPrint('Could not ask xcrun for the macOS SDK: $e');
      return null;
    }
  }
}
