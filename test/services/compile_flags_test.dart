import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'package:classic_code_editor/services/compile_flags.dart';

void main() {
  late Directory workDir;

  setUp(() {
    workDir = Directory.systemTemp.createTempSync('compile_flags_test');
  });

  tearDown(() {
    if (workDir.existsSync()) workDir.deleteSync(recursive: true);
  });

  File flagsFile() =>
      File('${workDir.path}${Platform.pathSeparator}compile_flags.txt');

  test('writes compile_flags.txt with the SDK sysroot when it is missing', () async {
    final ensurer = CompileFlagsEnsurer(
      sdkPathResolver: () async => '/Applications/Xcode.app/SDKs/MacOSX.sdk',
    );

    final outcome = await ensurer.ensure(workDir.path);

    expect(outcome, CompileFlagsOutcome.created);
    final contents = flagsFile().readAsStringSync();
    expect(contents, contains('-isysroot /Applications/Xcode.app/SDKs/MacOSX.sdk'));
    expect(contents, contains('# Generated by Classic Code Editor'));
  });

  test('never overwrites a user-authored file', () async {
    final file = flagsFile()..writeAsStringSync('-std=c17\n-Icustom\n');
    final ensurer = CompileFlagsEnsurer(sdkPathResolver: () async => '/SDK');

    final outcome = await ensurer.ensure(workDir.path);

    expect(outcome, CompileFlagsOutcome.alreadyPresent);
    expect(file.readAsStringSync(), '-std=c17\n-Icustom\n');
  });

  test('omits -isysroot when the SDK cannot be resolved', () async {
    final ensurer = CompileFlagsEnsurer(sdkPathResolver: () async => null);

    final outcome = await ensurer.ensure(workDir.path);

    expect(outcome, CompileFlagsOutcome.created);
    expect(flagsFile().readAsStringSync(), isNot(contains('-isysroot')));
  });

  test('reports unavailable without a directory', () async {
    final ensurer = CompileFlagsEnsurer(sdkPathResolver: () async => '/SDK');

    expect(await ensurer.ensure(null), CompileFlagsOutcome.unavailable);
    expect(await ensurer.ensure('  '), CompileFlagsOutcome.unavailable);
  });

  test('reports failed instead of throwing when the path is not writable', () async {
    final ensurer = CompileFlagsEnsurer(sdkPathResolver: () async => '/SDK');

    // A file where the directory should be: creates a FileSystemException.
    final blocker = File('${workDir.path}${Platform.pathSeparator}blocked')
      ..writeAsStringSync('not a directory');

    expect(await ensurer.ensure(blocker.path), CompileFlagsOutcome.failed);
  });

  test('buildContents is stable for a missing SDK', () {
    final contents = CompileFlagsEnsurer.buildContents(null);

    expect(contents.split('\n').where((line) => line.isNotEmpty), hasLength(2));
    expect(contents, isNot(contains('-isysroot')));
  });
}
